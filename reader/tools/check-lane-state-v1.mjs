#!/usr/bin/env node
// GUARDS: lane-state-rule-v1-one-fetch-says-what-this-lane-is-serving
//
// A SUMMARY THAT DISAGREES WITH WHAT IT SUMMARIZES IS A LIE IN A SMALLER FONT.
//
// data/lane-state-v1.json exists so the corpus lane can learn what this lane
// is serving in one request instead of asking somebody who may be offline. A
// peer lane that fetches a stale summary is worse off than one that fetches
// nothing: it stops asking, and it is wrong.
//
// So every number in it is re-derived here from the artifact that owns it, and
// the file has to agree. That is the whole check. It is deliberately not clever
// — the summary is generated by a tool, so the only way it goes wrong is
// drifting behind what it describes, and drift is caught by recomputation and
// by nothing else.
//
// Three failures this shape has already had in this tree, none hypothetical:
//   · the store index said the shards weighed 14,641,140 bytes when 12,898,585
//     were on disk, because the strike that shrank them updated keys and routes
//     and not the weight
//   · the index said 4 admission rounds against the record's 3, because the
//     sync compared one field and 49 equalled 49
//   · the admission counts said 27 sources and 79,095 routes beside a list of
//     49 ids, and the unlabelled figure travelled to the peer lane as the
//     whole strike
//
// Run: node tools/check-lane-state-v1.mjs
import { readFileSync, existsSync, readdirSync } from "node:fs";
import { gunzipSync } from "node:zlib";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { zonesOnDisk, zonesServed } from "./zones-on-disk-v1.mjs";
import { LANE_STATE_RULE_ID } from "./emit-lane-state-v1.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const K3 = join(HERE, "..");
const STATE = join(K3, "data", "lane-state-v1.json");
const STORE = join(K3, "data", "route-store");
const ZONES = join(K3, "data", "zones");

let bad = 0;
const check = (n, ok, d = "") => { if (!ok) bad += 1; console.log(`${ok ? "  ok  " : "FAIL  "}${n}${d ? "  ·  " + d : ""}`); };

if (!existsSync(STATE)) {
  console.log("SKIPPED — data/lane-state-v1.json is not here; run tools/emit-lane-state-v1.mjs");
  process.exit(3);
}
const s = JSON.parse(readFileSync(STATE, "utf8"));
const index = JSON.parse(readFileSync(join(STORE, "index.json"), "utf8"));
const la = index.language_admission || {};
const cum = la.cumulative || {};

console.log(`— ${LANE_STATE_RULE_ID} —`);

check("S1  the file names the rule it keeps", s.rule_id === LANE_STATE_RULE_ID, s.rule_id || "(none)");

// S2 · the store. Sources counted off the index's own records, routes and keys
// off its counts, files off the manifest — each from its owner, never from
// another copy of the summary.
const manifest = JSON.parse(readFileSync(join(STORE, "store-manifest-v1.json"), "utf8"));
const storeWant = {
  version: index.store_version,
  sources: Object.keys(index.m_sources || {}).length,
  keys: (index.counts || {}).keys,
  routes: (index.counts || {}).routes,
  shards: (index.counts || {}).shards,
  files_pinned: Object.keys(manifest.files || {}).length,
};
const storeGot = Object.fromEntries(Object.keys(storeWant).map((k) => [k, s.store[k]]));
check("S2  the store it names is the store on disk",
  JSON.stringify(storeWant) === JSON.stringify(storeGot),
  JSON.stringify(storeWant) === JSON.stringify(storeGot)
    ? `${storeWant.version} · ${storeWant.sources} sources · ${storeWant.routes.toLocaleString()} routes`
    : `says ${JSON.stringify(storeGot)}, disk says ${JSON.stringify(storeWant)}`);

// S3 · the strike, and the one thing about it that must be cumulative. This
// number is the reason the file exists: it is what a peer lane differences its
// own store against.
check("S3  the strike it reports is cumulative and matches the record",
  s.language_admission.sources_struck === (la.struck_m_ids || []).length
    && s.language_admission.sources_struck === cum.sources_struck
    && s.language_admission.routes_struck === (Object.prototype.hasOwnProperty.call(cum, "routes_struck") ? cum.routes_struck : null)
    && s.language_admission.rounds === la.rounds,
  `${s.language_admission.sources_struck} sources · ${(s.language_admission.routes_struck || 0).toLocaleString()} routes · ${s.language_admission.rounds} round(s)`);
check("S4  and it says which two stores that figure was measured between",
  s.language_admission.routes_struck === null
    || (s.language_admission.measured_between
      && s.language_admission.measured_between.after === index.store_version),
  s.language_admission.measured_between
    ? `${s.language_admission.measured_between.before} -> ${s.language_admission.measured_between.after}`
    : "no pair named");
// The reason census has to sum to the strike, or one bucket is standing for
// the whole of it — which is the substitution this lane spent the day undoing.
const reasons = s.language_admission.reasons || {};
const reasonSum = Object.values(reasons).reduce((a, b) => a + b, 0);
check("S5  the reasons sum to the strike, so no one reason stands for all of it",
  reasonSum === s.language_admission.sources_struck,
  `${Object.entries(reasons).map(([r, n]) => `${n} ${r.split("__")[0].toLowerCase().replace(/_/gu, " ")}`).join(" · ")} = ${reasonSum}`);

// S6 · the shelf, counted the way the door counts it.
const onDisk = zonesOnDisk().length, served = zonesServed().length;
check("S6  the shelf it reports is the shelf on disk",
  s.shelf.zones_on_disk === onDisk && s.shelf.zones_served === served && s.shelf.withheld === onDisk - served,
  `${s.shelf.zones_served} served of ${s.shelf.zones_on_disk} on disk`);

// S7 · the sidecars, counted off the files rather than off the summary.
const files = existsSync(ZONES) ? readdirSync(ZONES) : [];
const sidecarWant = {};
for (const [name, suffix] of [["commentary", ".commentary.bin"], ["hoh", ".hoh.bin"], ["lattice", ".lattice.bin"], ["volume", ".volume.bin"]])
  sidecarWant[name] = files.filter((f) => f.endsWith(suffix)).length;
const sidecarBad = Object.entries(sidecarWant).filter(([n, want]) => ((s.shelf.sidecars || {})[n] || {}).books !== want);
check("S7  every kind of sidecar is counted, including the kinds with none",
  sidecarBad.length === 0 && Object.keys(s.shelf.sidecars || {}).length === Object.keys(sidecarWant).length,
  sidecarBad.length ? sidecarBad.map(([n, w]) => `${n}: says ${((s.shelf.sidecars || {})[n] || {}).books}, disk has ${w}`).join(" · ")
    : Object.entries(sidecarWant).map(([n, w]) => `${n} ${w}`).join(" · "));

// S8 · the lattice, reported as a SET of schemas. One version number here
// would be a claim the shelf is uniform, which is the thing a peer lane is
// fetching this to check — so the check asserts the shape, not the count.
const schemas = new Set();
let latticeBooks = 0;
for (const b of zonesServed()) {
  const p = join(ZONES, `${b}.lattice.bin`);
  if (!existsSync(p)) continue;
  latticeBooks += 1;
  const l = JSON.parse(gunzipSync(readFileSync(p)).toString("utf8"));
  schemas.add(`${(l.source || {}).schema} · ${(l.source || {}).generated}`);
}
check("S8  the lattice is reported as every schema present, not as one version",
  Array.isArray(s.lattice.schemas_present)
    && s.lattice.books_carrying_one === latticeBooks
    && s.lattice.schemas_present.length === schemas.size
    && s.lattice.schemas_present.every((x) => schemas.has(x.schema_and_generated)),
  `${latticeBooks} book(s), ${schemas.size} schema(s): ${[...schemas].join(" | ")}`);

// S9 · every block says what it was counted over. The law this whole file is
// written under, asserted on the file itself.
const blocks = ["store", "language_admission", "shelf", "lattice", "counts_layer"];
const noScope = blocks.filter((b) => typeof (s[b] || {}).scope !== "string" || !s[b].scope.trim());
check("S9  every block says what it was counted over",
  noScope.length === 0, noScope.length ? `no scope on: ${noScope.join(", ")}` : `${blocks.length} blocks, each with its set named`);

// S10 · and it says what it is not. A state file reads as complete.
check("S10 it names what it does not say",
  Array.isArray(s.what_this_does_not_say) && s.what_this_does_not_say.length >= 3,
  `${(s.what_this_does_not_say || []).length} things it declines to claim`);

// S11 · NOTHING FROM ANYBODY'S MACHINE. This file is published, and the peer
// lane's own ledgers carry absolute paths off a personal computer. Anything
// picked up from them and copied here would be deployed to a public branch.
const body = readFileSync(STATE, "utf8");
const leaks = [
  [/[A-Za-z]:\\\\/u, "a Windows drive path"],
  [/\/(?:home|Users)\//u, "a home directory path"],
  [/\b[\w.+-]+@[\w-]+\.[\w.]+\b/u, "an email address"],
];
const found = leaks.filter(([re]) => re.test(body));
check("S11 it carries nothing off anybody's machine",
  found.length === 0, found.length ? found.map(([, w]) => w).join(" · ") : `${body.length.toLocaleString()} bytes, no path and no address`);

console.log(bad ? `\n${bad} FAILED` : "\nall checks passed");
process.exit(bad ? 1 : 0);
