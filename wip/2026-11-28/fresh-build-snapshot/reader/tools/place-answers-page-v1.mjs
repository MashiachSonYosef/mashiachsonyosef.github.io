// LEDGER: -
// no frame letter. The shape of data/place-answers-v1/page/ said once, and
// the rules by which it is projected from the places, the entries and the
// bridges. It reads nothing by itself and writes nothing.
//
// WHY THIS IS A FILE. The second reader (reader/place.html) shows the 39
// books from the place answers alone. Its files are a projection by rule:
// tools/project-place-answers-page-v1.mjs writes them, and
// tools/check-place-answers-page-v1.mjs holds every string of them to the
// places and the entries. The two must agree on the shape, on which keys of a
// dictionary's entry the page leaves out, on how a tag and a record are filed
// into small files, and on the few sentences that are ours (how our text and
// STEP's meet at a word). Those live here. What the check must NOT share
// with the projection is the finding of a source's answer at a place: the
// check looks every such answer up again in the bridges and the entries by
// the address the page file states.
//
// THE RULE OF THE PAGE. The card shows what each source says here, by that
// source's own address, and then each dictionary's own entry. Nothing is
// matched by letters; there is no pool of readings.
//
//   STEP        the row or rows our word meets (the places), each part with
//               its English exactly as STEP writes it and its tag
//   MACULA      the word's morphs with MACULA's two English columns
//   UBS         the senses that cite this very word: the dictionary cites
//               verse and word. Its word number is in no other file; it is
//               reckoned through MACULA's morph rows (twice the place of the
//               morph row in the verse, suffixes and the Aramaic article
//               ending not counted, a word number MACULA's table skips
//               counted as one: measured by the places' builder, 96.4 in 100)
//               and CORROBORATED at every word: a sense is laid on the word
//               only where its entry is one the word's tag reaches, or its
//               lemma is MACULA's lemma for the morph. Where the tag's entry
//               cites the verse at another number, that is said as a citation
//               of the verse, never as this word's.
//   BDB         (both files) of the entries the word's tag reaches, the
//               senses that cite this verse. BDB cites a verse, not a word.
//
// A RECORD OF ANOTHER WORD IS NEVER SHOWN AT THIS WORD (the second cut, 27
// November 2026). The unabridged BDB's number column is a loose list: one
// number stands on up to nine records, and a record's paragraphs can be
// several words (the record of «if» also holds «mother» and «cubit»). So a
// paragraph of a record is this word's only where its own headword has the
// letters of the word's lemma as a source gives it: STEP's brief lexicon's
// headword for the number, or the Lexical Index's, or MACULA's lemma for a
// morph of the word that carries the number. Letters are compared as the
// places compare them: consonants only, the five end-of-word shapes folded.
// A citing paragraph that fails this is not said to cite the place. The same
// test parts an ambiguous number: each tag's line names the records (and
// their paragraphs) whose headword has the lemma's letters by the first two
// sources (own), and a form names the records that are its word's by
// MACULA's lemma alone (ow).
//
// STEP'S HEADWORD IS READ WITHOUT ITS SQUARE BRACKETS (the third cut, 27
// November 2026). STEP's brief lexicon writes square brackets in five
// headwords. Each is the headword of a number that is one word of a
// combination: its relation column says so («a Part of», «combination of»,
// «a Meaning of»), and the brackets hold the combination's other words. The
// word the number stands on is therefore the headword outside the brackets,
// and for the headword test above STEP's headword is read without its
// square-bracketed runs (stepsOwnHeadword). The pin names the headwords so
// read, each with its relation as the file gives it.
//
// THE DECLARED LANGUAGE PARTS THE RECORDS (the fifth cut, 27 November 2026).
// STEP's brief lexicon says in its morph column whether a number's word is
// Hebrew or Aramaic (every part of the column opens with H: or A:; a name
// opens with N: and says neither). Each record of the unabridged BDB says
// its own language in its own line. Where STEP says the language of the
// number and the record says its own, a record of the other language is not
// this word's: a citing paragraph of it is not said to cite the place, and
// each tag's line names the language (lg) and the records the number
// reaches that are of the other (ol), so that the reader sets them behind
// and says why. Nothing of ours is compared but the two declarations; where
// either source does not say, the letters decide as before.
//
// THE LANGUAGE IS THE ROW'S AT THIS WORD (the sixth cut, 27 November 2026).
// STEP's brief lexicon gives one language a number, and it can be wrong for
// a word: it says Hebrew for «god» (H0426) where every one of STEP's 95
// rows of it, in Daniel and Ezra, says Aramaic. Each of STEP's rows says its
// own language in its grammar column (it opens with H or A), and the places
// hand every part its row's language. So the language of a word is what
// STEP's row at this very word says for the number (rowsLanguage); the
// lexicon's morph column is read only where the row says neither. The form
// carries its rows' language (t.lg) and the unabridged BDB's records its
// numbers reach that are of the other language at this word (ol): the card
// sets those behind under «In the dictionaries», word by word. A tag's line
// keeps only what the lexicon says (lg), for a row that says nothing.
//
// THE STEM STANDS ON THE LINE (the sixth cut). The unabridged BDB numbers a
// verb's senses afresh under each stem, and the entries reader keeps the
// stem headings of each paragraph; the verse bridge says, for each
// reference, the heading it stands under and whether it stands in that
// stem's own head (its list of forms, before any numbered point of it). A
// «cites this verse» line names the stem with the point (unabridgedLine):
// the point's label where it stands in a point, nothing but the stem where
// it stands in the stem's head; its italics are the unit's own, up to the
// next stem heading inside the unit, or from the heading on for a stem's
// head, each run with the kind the entries file classes it as (the card
// quotes only the entry's meaning and the words a unit opens with, and needs
// no record to tell them; the eighth cut). Where a verse stands both in a
// stem's head and in a numbered point
// of the same stem, the point leads (pointsLead). A point whose label the
// file writes with another stem's name (a cross-reference glued to the
// point: «Qal 2. 2.» under Hiph`il) keeps its label, marked as naming
// another stem than the one the line stands under.
//
// STEP's row is followed where it says otherwise than the passage: at
// Genesis 31:47 it marks Laban's Aramaic name «Jegar-sahadutha» as Hebrew
// (words 4 and 5; MACULA says Aramaic there, and these are the only two
// words of the 39 books where the two differ), so that name's one record,
// of the Aramaic part of BDB, stands behind for its language. Decided
// (seventh cut): no exception; the place is listed for the corpus lane.
//
// BDB'S OWN HOMONYM NUMERAL (the seventh cut). Both BDB files print the
// work's own numeral for words of the same letters: «II.» before the
// unabridged record's headword, mod="II" on the Open Scriptures entry. The
// Open Scriptures entry a number reaches is exact (STEP's letter and the
// Lexical Index), so under that number the unabridged record that bears the
// same numeral is the same entry of the same work: two editions of one
// dictionary met by the dictionary's own label (osNumeral). Among the
// records that pass the headword and language tests, one whose own
// paragraph bears another numeral goes behind (a tag's on, its numeral nm),
// and a citing paragraph of another numeral is not said to cite this word.
// Where the entry has no numeral, or the records carry none, nothing
// changes; the numeral orders and parts, it never takes a record away.
// A citing paragraph of another numeral is BDB's own reading where it puts
// its word here (Exod 30:33: BDB files «cut off from his kinsmen» under II.
// «kinsman» where STEP's letter reads I. «people»), so the two readings are
// shown, not BDB's silenced: the line is drawn with a mark that carries the
// paragraph's numeral, its gloss and the entry's numeral (its 16th field),
// unless BDB's quoted form names another word of the verse that carries
// the number; then it is that word's and is not drawn (partRecurring).
// Nor is it drawn where every reference behind it is BDB's pointer, not its
// reading: one BDB follows, over other references only, with «see» (not
// «see also», not «see» and a reference) or «read» («— Num 24:6 see II.»,
// «(Lev 19:16 read …»), or one inside a bracket that names a homonym of
// another numeral («(II. …, compare Ps 16:8)»). There BDB itself sends the
// verse elsewhere (pointsElsewhere). «compare» alone is BDB's own reading
// («compare Exod 30:33» under II. «kinsman» is drawn). Nor where another
// word of the verse holds the same paragraph as its own numeral's: BDB's
// «heap» at Judg 15:16 is the second «chamor»'s, not the ass's; its
// «thorns» at Eccl 7:6 are «ha-sirim», not «the pot».
//
// ONE RECORD CITED AT TWO WORDS OF A VERSE (the seventh cut). BDB cites a
// verse, not a word. Where a number stands at two or more words of the
// verse, a «cites this verse» line may be another word's. BDB writes the
// form it means right before the reference («Participle» and the form, then «Gen 1:11»), and
// that form, with the verse, is its own address for the word, as the UBS
// dictionary's word number is. So (partRecurring): where every reference
// behind a line quotes the letters of another occurrence and not this
// word's (consonants, end shapes folded, word by word, against each
// occurrence's letters as our text writes it, each form of a pair, and
// the same with one or two proclitic letters taken off its front, which
// BDB's quotes often leave off; the
// file's words a maqaf joined are parted where it marks them; a run two or
// more of whose words are no word of this verse quotes another verse), the
// line is that word's and not this one's; it stands at the named word,
// whose own tests draw it there. Where no form is quoted, or the quoted
// forms do not part the occurrences, the line stays and is marked with how
// many words the number stands on, so that the card says once that BDB
// does not say which word it means.
//
// A WORD WRITTEN ONE WAY AND READ ANOTHER (the sixth cut). BDB cites the
// verse, and both forms of such a word reach the same records, so a line of
// the stem of one form stood on both. STEP's grammar gives each form its stem
// (the read form from its row, the written form from its K= variant). Where
// a line's stem is the one form's and not the other's, it stands on that form
// only (partPairLines). Elsewhere it stays on both. A stem is named across
// the two sources by one table: STEP's letters as the Open Scriptures codes
// define them (stepsStem), BDB's names as this file writes them (bdbsStem).
//
// THE LINE UNDER A WORD IS THE READER'S LINE. STEP's parts joined with « + »
// as the live reader draws them at rest: a part that is only a sign is not
// drawn (a hidden sign's gap stands in its place, and no joiner beside it),
// and where every part is a sign they stand. The pieces and the joiner are
// the reader's own (tools/gloss-store-v1.mjs: printedForm, signOnly,
// joinDrawn), used here and not said again. «Every part is a sign» is judged
// as the live reader judges it: over the words a maqaf ties into one run
// (plain words, each but the last ending in a maqaf), so the object marker
// before its noun is a gap, and standing alone it shows its sign. A form
// carries the drawn line (g) only where it is not simply its parts trimmed
// and joined; the card keeps STEP's words exactly.
//
// No Hebrew letter stands in this file: a letter is named by its code point.
