// One section's export, taken as the page writes it, and printed. node probe-export.mjs <reader dir> <zone url base> <book> <section label> [nth form, 1..3] [out file]
import { pathToFileURL } from "node:url";
import { join } from "node:path";
import { readFileSync, writeFileSync } from "node:fs";
const [reader, base, book, label, nthArg, outFile] = process.argv.slice(2);
const nth = Number(nthArg || 1);
const { loadPlaywright, launchOptions } = await import(pathToFileURL(join(reader, "tools", "playwright-v1.mjs")).href);
const pw = await loadPlaywright();
const b = await pw.chromium.launch(launchOptions());
const p = await b.newPage({ viewport: { width: 412, height: 915 }, acceptDownloads: true });
p.on("pageerror", (e) => console.log("PAGE ERROR:", e.message));
await p.goto(`${base}?b=${book}`, { waitUntil: "networkidle" });
await p.waitForSelector("section.seg .he-text .wb");
const idx = await p.evaluate((label) => (window.__zone.sections || []).findIndex((s) => s.label === label), label);
await p.evaluate(async (idx) => { const s = document.getElementById(`s${idx}`); for (let g = 0; g < 400 && s && !s.querySelector(".he-text .wb"); g += 1) { s.scrollIntoView({ block: "center" }); await new Promise((r) => setTimeout(r, 25)); } s.scrollIntoView({ block: "center" }); }, idx);
await p.waitForTimeout(600);
const sec = `#s${idx}`;
await p.evaluate((sec) => { const s = document.querySelector(sec); const m = s.querySelector(".xp-menu"); if (!m || m.hidden) s.querySelector(".xp-open").click(); }, sec);
await p.waitForSelector(`${sec} .xp-menu .xp-row .xp`);
const rows = await p.evaluate((sec) => [...document.querySelectorAll(`${sec} .xp-menu .xp-row`)].map((r) => [...r.querySelectorAll(".xp")].map((x) => x.textContent.trim())), sec);
console.log("menu rows:", JSON.stringify(rows));
await p.click(`${sec} .xp-row .xp:nth-of-type(${nth})`);
await p.waitForFunction((sec) => /Press again|Refused/.test(document.querySelector(`${sec} .xp-note`)?.textContent || ""), sec, { timeout: 30000 });
console.log("note:", await p.evaluate((sec) => document.querySelector(`${sec} .xp-note`).textContent, sec));
const [dl] = await Promise.all([p.waitForEvent("download"), p.click(`${sec} .xp-row .xp.armed`)]);
const text = readFileSync(await dl.path(), "utf8");
if (outFile) writeFileSync(outFile, text);
console.log(`--- ${dl.suggestedFilename()} (${text.length} characters)`);
console.log(text);
await b.close();
